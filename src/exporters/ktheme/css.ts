import type { EdgeInsets, HexColor } from '@/domain/theme/types'
import { ADAPTER_VERSION } from './catalog'

/**
 * Serializer for KakaoTalkTheme.css. Selector and property names are copied from
 * the reference archive only; web CSS (border-radius etc.) is never emitted.
 */

export interface BubbleCss {
  image: string
  selectedImage: string
  groupImage: string
  groupSelectedImage: string
  stretch: { x: number; y: number }
  groupStretch: { x: number; y: number }
  insets: EdgeInsets
  groupInsets: EdgeInsets
  textColor: HexColor
  selectedTextColor: HexColor
  unreadTextColor: HexColor
}

export interface ThemeCssModel {
  manifest: { name: string; version: string; id: string; author: string; url: string }
  tabBar: {
    backgroundColor: HexColor | null
    backgroundImage: string | null
    icons: { cssKey: string; normal: string; selected: string }[]
  }
  header: { text: HexColor; tabText: HexColor; tabHighlightedText: HexColor }
  main: {
    backgroundColor: HexColor
    backgroundImage: string
    title: HexColor
    titleHighlighted: HexColor
    description: HexColor
    paragraph: HexColor
    cellColor: HexColor
    secondaryBackground: HexColor
    sectionBorder: HexColor
    sectionText: HexColor
    featureText: HexColor
  }
  profileImage: string
  chatroom: { backgroundColor: HexColor; backgroundImage: string }
  inputBar: { background: HexColor; sendBackground: HexColor; sendForeground: HexColor; button: HexColor }
  send: BubbleCss
  receive: BubbleCss
  passcode: {
    backgroundColor: HexColor
    backgroundImage: string
    title: HexColor
    bullets: string[]
    selectedBullets: string[]
    keypadBackground: HexColor
    keypadText: HexColor
    keypadPressedImage: string
  }
  notificationBar: { background: HexColor; name: HexColor; message: HexColor }
}

/** Number → `12px` / `16.5px` (max one decimal, as in the reference). */
export const px = (n: number) => `${Number(n.toFixed(1))}px`
const img = (base: string) => `'${base}.png'`
const ORDINALS = ['first', 'second', 'third', 'fourth'] as const

/** Strips characters that would break a quoted CSS string or comment. */
export function cssString(value: string): string {
  return value
    .normalize('NFC')
    // eslint-disable-next-line no-control-regex -- stripping control characters is the point
    .replace(/[\u0000-\u001f\u007f'"\\]/g, '')
    .replace(/\*\//g, '')
    .trim()
}

/** Empty blocks are omitted (the reference never contains one). */
function block(selector: string, lines: (string | false | null)[]): string {
  const body = lines.filter(Boolean).map((l) => `    ${l}`)
  if (!body.length) return ''
  return `${selector}\n{\n${body.join('\n')}\n}\n`
}

const insets = (i: EdgeInsets) => `${px(i.top)} ${px(i.left)} ${px(i.bottom)} ${px(i.right)}`

function bubbleBlock(selector: string, b: BubbleCss): string {
  return block(selector, [
    `-ios-background-image: ${img(b.image)} ${px(b.stretch.x)} ${px(b.stretch.y)};`,
    `-ios-selected-background-image: ${img(b.selectedImage)} ${px(b.stretch.x)} ${px(b.stretch.y)};`,
    `-ios-group-background-image: ${img(b.groupImage)} ${px(b.groupStretch.x)} ${px(b.groupStretch.y)};`,
    `-ios-group-selected-background-image: ${img(b.groupSelectedImage)} ${px(b.groupStretch.x)} ${px(b.groupStretch.y)};`,
    `-ios-title-edgeinsets: ${insets(b.insets)};  /* top, left, bottom, right */`,
    `-ios-group-title-edgeinsets: ${insets(b.groupInsets)};`,
    `-ios-text-color: ${b.textColor};`,
    `-ios-selected-text-color: ${b.selectedTextColor};`,
    `-ios-unread-text-color: ${b.unreadTextColor};`,
  ])
}

export function serializeThemeCss(m: ThemeCssModel): string {
  const parts = [
    `/*\n Generated by Kakao Theme Studio (adapter ${ADAPTER_VERSION})\n */\n`,
    block('ManifestStyle', [
      `-kakaotalk-theme-name: '${cssString(m.manifest.name)}';`,
      `-kakaotalk-theme-version: '${cssString(m.manifest.version)}';`,
      `-kakaotalk-theme-url: '${cssString(m.manifest.url)}';`,
      `-kakaotalk-author-name: '${cssString(m.manifest.author)}';`,
      `-kakaotalk-theme-id: '${cssString(m.manifest.id)}';`,
    ]),
    block('TabBarStyle-Main', [
      m.tabBar.backgroundColor && `background-color: ${m.tabBar.backgroundColor};`,
      m.tabBar.backgroundImage && `-ios-background-image: ${img(m.tabBar.backgroundImage)};`,
      ...m.tabBar.icons.flatMap((t) => [
        `-ios-${t.cssKey}-normal-icon-image: ${img(t.normal)};`,
        `-ios-${t.cssKey}-selected-icon-image: ${img(t.selected)};`,
      ]),
    ]),
    block('HeaderStyle-Main', [
      `-ios-text-color: ${m.header.text};`,
      `-ios-tab-text-color: ${m.header.tabText};`,
      `-ios-tab-highlighted-text-color: ${m.header.tabHighlightedText};`,
    ]),
    block('MainViewStyle-Primary', [
      `background-color: ${m.main.backgroundColor};`,
      `-ios-background-image: ${img(m.main.backgroundImage)};`,
      `-ios-text-color: ${m.main.title};`,
      `-ios-highlighted-text-color: ${m.main.titleHighlighted};`,
      `-ios-description-text-color: ${m.main.description};`,
      `-ios-description-highlighted-text-color: ${m.main.description};`,
      `-ios-paragraph-text-color: ${m.main.paragraph};`,
      `-ios-paragraph-highlighted-text-color: ${m.main.paragraph};`,
      `-ios-normal-background-color: ${m.main.cellColor};`,
      `-ios-normal-background-alpha: 0.0;`,
      `-ios-selected-background-color: ${m.main.title};`,
      `-ios-selected-background-alpha: 0.05;`,
    ]),
    block('MainViewStyle-Secondary', [`background-color: ${m.main.secondaryBackground};`]),
    block('SectionTitleStyle-Main', [
      `border-color: ${m.main.sectionBorder};`,
      `border-alpha: 1.0;`,
      `-ios-text-color: ${m.main.sectionText};`,
      `-ios-text-alpha: 1.0;`,
    ]),
    block('FeatureStyle-Primary', [`-ios-text-color: ${m.main.featureText};`]),
    block('DefaultProfileStyle', [`-ios-profile-images: ${img(m.profileImage)};`]),
    block('BackgroundStyle-ChatRoom', [
      `background-color: ${m.chatroom.backgroundColor};`,
      `-ios-background-image: ${img(m.chatroom.backgroundImage)};`,
    ]),
    block('InputBarStyle-Chat', [
      `background-color: ${m.inputBar.background};`,
      `-ios-send-normal-background-color: ${m.inputBar.sendBackground};`,
      `-ios-send-normal-foreground-color: ${m.inputBar.sendForeground};`,
      `-ios-send-highlighted-background-color: ${m.inputBar.sendBackground};`,
      `-ios-send-highlighted-foreground-color: ${m.inputBar.sendForeground};`,
      `-ios-button-normal-foreground-color: ${m.inputBar.button};`,
      `-ios-button-highlighted-foreground-color: ${m.inputBar.button};`,
    ]),
    bubbleBlock('MessageCellStyle-Send', m.send),
    bubbleBlock('MessageCellStyle-Receive', m.receive),
    block('BackgroundStyle-Passcode', [
      `background-color: ${m.passcode.backgroundColor};`,
      `-ios-background-image: ${img(m.passcode.backgroundImage)};`,
    ]),
    block('LabelStyle-PasscodeTitle', [`-ios-text-color: ${m.passcode.title};`]),
    block('PasscodeStyle', [
      ...m.passcode.bullets.map((b, i) => `-ios-bullet-${ORDINALS[i]}-image: ${img(b)};`),
      ...m.passcode.selectedBullets.map((b, i) => `-ios-bullet-selected-${ORDINALS[i]}-image: ${img(b)};`),
      `-ios-keypad-background-color: ${m.passcode.keypadBackground};`,
      `-ios-keypad-text-normal-color: ${m.passcode.keypadText};`,
      `-ios-keypad-number-highlighted-image: ${img(m.passcode.keypadPressedImage)};`,
    ]),
    block('BackgroundStyle-MessageNotificationBar', [`background-color: ${m.notificationBar.background};`]),
    block('LabelStyle-MessageNotificationBarName', [`-ios-text-color: ${m.notificationBar.name};`]),
    block('LabelStyle-MessageNotificationBarMessage', [`-ios-text-color: ${m.notificationBar.message};`]),
  ]
  return parts.filter(Boolean).join('\n')
}

export type ParsedCss = Map<string, Map<string, string>>

/** Tolerant parser for the theme CSS dialect (selector { prop: value; }), comments stripped. */
export function parseThemeCss(source: string): ParsedCss {
  const text = source.replace(/^\uFEFF/, '').replace(/\/\*[\s\S]*?\*\//g, '')
  const out: ParsedCss = new Map()
  const blockRe = /([A-Za-z][\w-]*)\s*\{([^}]*)\}/g
  for (const match of text.matchAll(blockRe)) {
    const props = out.get(match[1]) ?? new Map<string, string>()
    for (const decl of match[2].split(';')) {
      const idx = decl.indexOf(':')
      if (idx < 0) continue
      const key = decl.slice(0, idx).trim()
      const value = decl.slice(idx + 1).trim()
      if (key) props.set(key, value)
    }
    out.set(match[1], props)
  }
  return out
}

/** All `'name.png'` image references in the CSS, as base names. */
export function referencedImages(source: string): Set<string> {
  const text = source.replace(/\/\*[\s\S]*?\*\//g, '')
  return new Set(Array.from(text.matchAll(/'([^'\s]+)\.png'/g), (m) => m[1]))
}
